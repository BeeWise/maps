#!/usr/bin/env node
// Sync/check the Objective-C interface emitted when compiling the RNMBXSwift target.
const fs = require('node:fs');
const path = require('node:path');
const args = process.argv.slice(2);
const check = args.includes('--check');
const source = args.find(arg => arg !== '--check');
if (!source) throw new Error('Usage: node scripts/sync-spm-swift-interface.cjs [--check] /path/to/Objects-normal/arm64/RNMBXSwift-Swift.h');
let contents = fs.readFileSync(source, 'utf8');
if (contents.startsWith('#if 0')) throw new Error('Use the per-architecture Objects-normal header, not the merged GeneratedModuleMaps header.');
if (!contents.includes('#ifndef RNMBXSWIFT_SWIFT_H')) throw new Error('Not an RNMBXSwift compiler-generated interface');
contents = '// Generated Objective-C interface for RNMBXSwift. See SPM.md for regeneration.\n' + contents.replace(/^\/\/ Generated by Apple Swift version.*\n/m, '');
contents = contents.replace(/[ \t]+$/gm, '');
const destination = path.join(__dirname, '../ios/spm/RNMBXSwiftInterop.h');
if (check) {
  if (fs.readFileSync(destination, 'utf8') !== contents) throw new Error('Swift interface changed; run this command without --check and review the diff.');
  console.log('Swift interface matches.');
} else {
  fs.writeFileSync(destination, contents);
  console.log('Updated ios/spm/RNMBXSwiftInterop.h');
}
